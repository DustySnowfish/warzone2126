#!/usr/bin/env python3
"""Warzone 2126: build the random skirmish maps from random_map.js.

For each entry in MAPS this writes, under data/mp/multiplay/maps/:
  <folder>/game.js     header (size, players, tileset tables) + the generator core
  <folder>/ttypes.ttp  terrain types for the tileset
  <folder>.gam         scroll limits covering the whole map
and keeps the matching block of data/mp/addon.lev up to date.

Run from anywhere:  python3 tools/w2126/mapgen/build_maps.py
"""

import json
import os
import re
import struct

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
MAPS_DIR = os.path.join(ROOT, "data", "mp", "multiplay", "maps")
TILESET_DIR = os.path.join(ROOT, "data", "base", "tileset")
LEV = os.path.join(ROOT, "data", "mp", "addon.lev")
CORE = os.path.join(os.path.dirname(__file__), "random_map.js")

# One map per tileset and player count. The size is chosen in the lobby (Random map settings);
# this is the default ("Auto") size for each player count.
PLAYER_COUNTS = [2, 4, 8, 10, 15]
DEFAULT_SIZE = {2: 128, 4: 192, 8: 256, 10: 384, 15: 512}
TILESET_ORDER = ["arizona", "urban", "rockie"]

TILESETS = {
    "arizona": ("arizona", "MULTI_CAM_1", "Arizona"),
    "urban": ("urban", "MULTI_CAM_2", "Urban"),
    "rockie": ("rockie", "MULTI_CAM_3", "Rockies"),
}
# Level names must be unique, so they carry the player count ("Random-Arizona-8")
MAPS = [("Random-%s-%d" % (TILESETS[ts][2], p), DEFAULT_SIZE[p], p, ts) for ts in TILESET_ORDER for p in PLAYER_COUNTS]
# Folders from earlier versions (fixed sizes), removed when the maps are rebuilt
OLD_FOLDERS = ["2c-Random-128-Arizona", "4c-Random-192-Urban", "4c-Random-256-Rockies", "8c-Random-256-Arizona",
               "8c-Random-384-Rockies", "8c-Random-512-Arizona", "10c-Random-512-Urban", "15c-Random-512-Rockies"]

FEATURE_STATS = os.path.join(ROOT, "data", "base", "stats", "features.json")


def tileset_tables(ts):
    prefix, _, types_key = TILESETS[ts]
    enum = open(os.path.join(TILESET_DIR, prefix + "_enum.txt")).read().split()[1:]
    ground_lines = [l.strip() for l in open(os.path.join(TILESET_DIR, prefix + "ground.txt")).read().splitlines()[1:]]
    tiles = []
    for line in ground_lines:
        parts = line.split(",")
        if len(parts) != 4:
            continue
        tiles.append([enum.index(p) for p in parts])
    decals = [int(x) for x in open(os.path.join(TILESET_DIR, prefix + "decals.txt")).read().split(",", 1)[1].split()]
    tt = json.load(open(os.path.join(TILESET_DIR, "tileTypes.json")))[types_key]
    all_types = [tt["Tile_%02d" % i] for i in range(len(tt))]
    feats = json.load(open(FEATURE_STATS))
    features = {k: [v.get("width", 1), v.get("breadth", 1)] for k, v in feats.items()}
    return {
        "name": ts,
        "ground": enum,
        "tiles": tiles,
        "types": all_types[: len(tiles)],
        "decals": decals,
        "features": features,
    }, all_types


def write_ttypes(path, types):
    with open(path, "wb") as f:
        f.write(b"ttyp")
        f.write(struct.pack("<II", 8, len(types)))
        f.write(struct.pack("<%dH" % len(types), *types))


def write_gam(path, size):
    # Scroll limits of 0 x 0 mean the whole map, whatever size the lobby picks
    data = bytearray(52)
    data[0:4] = b"game"
    struct.pack_into("<I", data, 4, 8)
    struct.pack_into("<II", data, 24, 0, 0)
    with open(path, "wb") as f:
        f.write(bytes(data))


def main():
    import shutil
    for old in OLD_FOLDERS:
        if os.path.isdir(os.path.join(MAPS_DIR, old)):
            shutil.rmtree(os.path.join(MAPS_DIR, old))
        if os.path.exists(os.path.join(MAPS_DIR, old + ".gam")):
            os.remove(os.path.join(MAPS_DIR, old + ".gam"))
    core = open(CORE).read()
    lev_entries = []
    for name, size, players, ts in MAPS:
        tables, all_types = tileset_tables(ts)
        folder = "%dc-Random-%s" % (players, TILESETS[ts][2])
        out_dir = os.path.join(MAPS_DIR, folder)
        os.makedirs(out_dir, exist_ok=True)
        header = (
            "// GENERATED by tools/w2126/mapgen/build_maps.py from random_map.js. Edit those, not this file.\n"
            "const MAP_SIZE = %d;\nconst PLAYERS = %d;\nconst TS = %s;\n\n" % (size, players, json.dumps(tables, separators=(",", ":")))
        )
        with open(os.path.join(out_dir, "game.js"), "w") as f:
            f.write(header + core)
        write_ttypes(os.path.join(out_dir, "ttypes.ttp"), all_types)
        write_gam(os.path.join(MAPS_DIR, folder + ".gam"), size)
        lev_entries.append(
            "level   %s\nplayers %d\ntype    14\ndataset %s\ngame    \"multiplay/maps/%s.gam\"\n"
            % (name, players, TILESETS[ts][1], folder)
        )
        print("wrote", folder)

    begin, end = "// W2126 random maps begin (generated)\n", "// W2126 random maps end\n"
    lev = open(LEV).read()
    block = begin + "\n".join(lev_entries) + end
    if begin in lev:
        lev = re.sub(re.escape(begin) + ".*?" + re.escape(end), lambda m: block, lev, flags=re.S)
    else:
        lev = lev.rstrip("\n") + "\n\n" + block
    open(LEV, "w").write(lev)
    print("updated addon.lev")


if __name__ == "__main__":
    main()
